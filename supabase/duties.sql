update public.industries set aliases = '{Friseurin,Barbier,Barber,Salon,Haare}' where key = 'friseur';

create or replace function public.industry_list()
returns table (key text, parent text, names jsonb, aliases text[], sort int)
language sql stable security invoker set search_path = public as $$
  select i.key, i.parent, i.names, i.aliases, i.sort from public.industries i where i.active order by i.sort, i.key
$$;
revoke all on function public.industry_list() from public, anon;
grant execute on function public.industry_list() to authenticated;

-- Branche vorschlagen (höchstens 20 Vorschläge je Konto)
create or replace function public.industry_suggest(p_name text, p_note text default null)
returns void language plpgsql security invoker set search_path = public as $$
begin
  if (select count(*) from public.industry_requests where owner = auth.uid()) >= 20 then raise exception 'too_many'; end if;
  insert into public.industry_requests (name, note) values (left(trim(p_name), 120), left(p_note, 2000));
end $$;
revoke all on function public.industry_suggest(text, text) from public, anon;
grant execute on function public.industry_suggest(text, text) to authenticated;

